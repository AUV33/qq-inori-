// addressed-judgment.mjs · 「先分清这轮是不是在说你」
//
// 为什么（2026-10-30）：群 123456789 里另一个 AI「小特的小鱼」在报自己的余额/花销，
// 她说出「围着一只鱼的余额算账」这句，说明看懂了对象，但整体仍把别人的账接成跟自己有关。
// 人设里已有「别把话都听成在说自己」，但那条是常态约束；这里在**唤醒时**加一步显式判断，
// 让她先对齐「他们在跟谁说话、说的是谁的事」，再决定接不接。
//
// 只对群聊注入：私聊就是两个人的场合，不存在"以为在说自己"的高频误判，别白花 token。
// 纯函数，零 IO，便于单测。

/**
 * @param {string} key 会话 key（group:123 / private:456）
 * @returns {string} 群聊返回提示块，其它情况返回空串
 */
export function addressedJudgmentLine(key) {
  if (!String(key ?? '').startsWith('group:')) return '';
  return [
    '【先分清这轮是不是在说你】看他们的话：在跟谁说话、说的是谁的事。',
    '- 有人@你、叫你名字、接你的话——那就是在说你，正常接。',
    '- 他们在聊自己的事（自己的账、余额、花销、别的 AI、不在场的人）——你只是路过；',
    '  想接就接那件事，别把他们的数字和处境接成你自己的，也别以为在点你。',
  ].join('\n');
}
